"""Apply the customizations Processa synced for: Visa Stamping.

Generated by Processa (Review Doctypes → Sync) for process map
``Visa Stamping Lifecycle - v1``. The data lives in the custom/ modules imported below --
this patch only applies it to a site that already exists.

Client Scripts are upserted by name, so re-running is harmless.
"""

import frappe
from one_fm.custom.client_script.visa_stamping import get_visa_stamping_client_scripts


def add_client_script(records):
	for rec in records:
		name = rec.get("name")
		values = {k: v for k, v in rec.items() if k != "name"}
		if frappe.db.exists("Client Script", name):
			doc = frappe.get_doc("Client Script", name)
			doc.update(values)
			doc.save(ignore_permissions=True)
		else:
			doc = frappe.get_doc({"doctype": "Client Script", **values})
			doc.name = name
			setattr(doc, "__newname", name)
			doc.insert(ignore_permissions=True)


def execute():
	add_client_script(get_visa_stamping_client_scripts())
